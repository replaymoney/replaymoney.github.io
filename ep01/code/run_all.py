"""Reproduce every number used in Episode 1 (and its stress tests).
Usage: python3 run_all.py      (numpy only; ~5-10 min)  -> results.json + results.md"""
import json, numpy as np, ai401k_model as M

INFL = 1.03 ** 40          # 3.262: nominal -> today's money
SEEDS = {"boom": 1, "fade": 2, "pop": 3}
BASE = dict(MU_REST=M.MU_REST, SIG_REST=M.SIG_REST, SIG_AI=M.SIG_AI, RHO=M.RHO, CASH=M.CASH, W_AI0=M.W_AI0)

def setp(**kw):
    for k, v in {**BASE, **kw}.items(): setattr(M, k, v)

def summarize(o):
    h, p, s = o["holder"] / INFL, o["panic"] / INFL, o["spread"] / INFL
    return dict(holder_median=float(np.median(h)), panic_median=float(np.median(p)), spread_median=float(np.median(s)),
                holder_p10=float(np.percentile(h, 10)), holder_p90=float(np.percentile(h, 90)),
                panic_vs_holder_paired_median=float(np.median(p / h) - 1), panic_beat_holder_share=float(np.mean(p > h)),
                panic_sold_at_least_once=float(o["panic_sold_share"]), spread_vs_holder_paired_median=float(np.median(s / h) - 1),
                holder_worst_ratio_first6y_median=float(np.median(o["worst_ratio_6y"])))

def run_set(n, **kw):
    setp(**kw)
    return {f: summarize(M.run(n=n, fate=f, seed=sd)) for f, sd in SEEDS.items()}

def panic_reentry(fate, seed, rule, n=4000):
    rng = np.random.default_rng(seed)
    ai, rest = M.market_paths(n, fate, rng); gai, grest = np.exp(ai), np.exp(rest)
    a = np.full(n, M.W_AI0); r = np.full(n, 1 - M.W_AI0); idx = np.empty((n, M.MONTHS))
    for t in range(M.MONTHS):
        a *= gai[:, t]; r *= grest[:, t]; idx[:, t] = a + r
    ret = idx / np.concatenate([np.ones((n, 1)), idx[:, :-1]], axis=1)
    h = np.full(n, M.START)
    for t in range(M.MONTHS): h = h * ret[:, t] + M.MONTHLY
    v = np.full(n, M.START); peak = v.copy(); inm = np.ones(n, bool); ipk = np.ones(n); sold_pk = np.zeros(n)
    out_m = np.zeros(n); low = np.full(n, np.inf)
    for t in range(M.MONTHS):
        now = idx[:, t]
        v = np.where(inm, v * ret[:, t], v * (1 + M.CASH) ** (1 / 12)) + M.MONTHLY
        ipk = np.maximum(ipk, now); peak = np.where(inm, np.maximum(peak, v), peak)
        sell = inm & (v < 0.70 * peak)
        sold_pk = np.where(sell, ipk, sold_pk); low = np.where(sell, now, low)
        inm = inm & ~sell
        out_m = np.where(inm, 0, out_m + 1); low = np.where(~inm, np.minimum(low, now), low)
        buy = {"old_peak": now >= sold_pk, "after_12_months": out_m >= 12, "after_6_months": out_m >= 6,
               "plus20_off_low": now >= 1.2 * low}[rule] & ~inm & ~sell
        inm |= buy; peak = np.where(buy, v, peak)
    return dict(panic_vs_holder_paired_median=float(np.median(v / h) - 1), panic_beat_holder_share=float(np.mean(v > h)))

R = {"parameters": dict(BASE, START=M.START, MONTHLY=M.MONTHLY, MONTHS=M.MONTHS, inflation_annual=0.03, seeds=SEEDS,
                        n_main=10000, n_tests=4000, numpy_version=np.__version__)}
print("main run (10,000 per future)..."); R["main"] = run_set(10000)
print("stress grid..."); R["stress_grid"] = {}
for mu in (0.075, 0.095, 0.11):
    for sig in (0.20, 0.25, 0.30):
        R["stress_grid"][f"return_{mu}_aivol_{sig}"] = run_set(4000, MU_REST=mu, SIG_AI=sig)
print("extra tests..."); R["cash_1pct"] = run_set(4000, CASH=0.01); R["corr_0.9"] = run_set(4000, RHO=0.90)
print("re-entry rules..."); setp(); R["reentry"] = {rule: {f: panic_reentry(f, sd, rule) for f, sd in SEEDS.items()}
                                     for rule in ("old_peak", "plus20_off_low", "after_12_months", "after_6_months")}
json.dump(R, open("results.json", "w"), indent=1)

def k(x): return f"${x/1e3:,.0f}K"
def pc(x): return f"{x:+.0%}"
L = ["# Episode 1 simulation results (generated by run_all.py)", "",
     "Today's money = nominal / 1.03^40. Medians across runs. Paired = same random market path for both investors.", "",
     "## Main run (10,000 per future)", "",
     "| | Boom | Cool-off | Pop |", "|---|---|---|---|"]
m = R["main"]; F = ("boom", "fade", "pop")
for lab, key, fmt in (("Holder median", "holder_median", k), ("Holder 10th pct", "holder_p10", k), ("Holder 90th pct", "holder_p90", k),
                      ("Panic-seller median", "panic_median", k), ("Panic vs holder (paired)", "panic_vs_holder_paired_median", pc),
                      ("Panic beat holder", "panic_beat_holder_share", lambda x: f"{x:.1%}"),
                      ("Panic sold at least once", "panic_sold_at_least_once", lambda x: f"{x:.0%}"),
                      ("Capped 3% portfolio vs holder (paired)", "spread_vs_holder_paired_median", pc),
                      ("Holder worst point in first 6 yrs / money put in", "holder_worst_ratio_first6y_median", lambda x: f"{x:.2f}")):
    L.append(f"| {lab} | " + " | ".join(fmt(m[f][key]) for f in F) + " |")
L += ["", "## Stress grid (4,000 per future)", "",
      "| Return (non-giants) | AI-giant vol | Holder boom/cool/pop | Panic vs holder | Panic beat holder | Best-future panic < worst-future holder |",
      "|---|---|---|---|---|---|"]
for key, r in R["stress_grid"].items():
    mu, sig = key.split("_")[1], key.split("_")[3]
    L.append(f"| {float(mu):.1%} | {float(sig):.0%} | " + "/".join(k(r[f]['holder_median']) for f in F) + " | "
             + "/".join(pc(r[f]['panic_vs_holder_paired_median']) for f in F) + " | "
             + "/".join(f"{r[f]['panic_beat_holder_share']:.0%}" for f in F) + " | "
             + ("yes" if r["boom"]["panic_median"] < r["pop"]["holder_median"] else "no") + " |")
for name, key in (("Cash yield 1% (instead of 3%)", "cash_1pct"), ("Correlation 0.9 (instead of 0.75)", "corr_0.9")):
    r = R[key]
    L += ["", f"## {name}", "", "| | Boom | Cool-off | Pop |", "|---|---|---|---|"]
    for lab, kk, fmt in (("Holder median", "holder_median", k), ("Panic vs holder", "panic_vs_holder_paired_median", pc),
                         ("Panic beat holder", "panic_beat_holder_share", lambda x: f"{x:.0%}"),
                         ("Capped 3% vs holder", "spread_vs_holder_paired_median", pc)):
        L.append(f"| {lab} | " + " | ".join(fmt(r[f][kk]) for f in F) + " |")
    L.append(f"\nBest-future panic < worst-future holder: {'yes' if r['boom']['panic_median'] < r['pop']['holder_median'] else 'no'}")
L += ["", "## Panic-seller buy-back rules (4,000 per future)", "", "| Rule | Panic vs holder (boom/cool/pop) | Panic beat holder |", "|---|---|---|"]
for rule, r in R["reentry"].items():
    L.append(f"| {rule} | " + "/".join(pc(r[f]['panic_vs_holder_paired_median']) for f in F) + " | "
             + "/".join(f"{r[f]['panic_beat_holder_share']:.0%}" for f in F) + " |")
open("results.md", "w").write("\n".join(L) + "\n")
print("done")
